namespace Barbatos.Pallas.Numerics;

/// <summary>
/// The unit an angle is expressed in.
/// </summary>
public enum AngleUnit
{
    /// <summary>Degrees: 360 per full turn.</summary>
    Degree = 0,

    /// <summary>Radians: 2π per full turn.</summary>
    Radian = 1,

    /// <summary>Gradians: 400 per full turn.</summary>
    Gradian = 2,
}
